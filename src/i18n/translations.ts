function getNested(obj: MessageTree, path: string): string | undefined {
  const parts = path.split('.');
  let current: string | MessageTree = obj;
  for (const part of parts) {
    if (typeof current !== 'object' || current === null) return undefined;
    current = current[part];
  }
  return typeof current === 'string' ? current : undefined;
}

export type TranslateFn = (
  key: string,
  vars?: Record<string, string | number>
) => string;

export function createTranslator(locale: Locale): TranslateFn {
  const messages = translations[locale];
  return (key: string, vars?: Record<string, string | number>) => {
    let text = getNested(messages, key) ?? getNested(translations.en, key) ?? key;
    if (vars) {
      Object.entries(vars).forEach(([k, v]) => {
        text = text.replaceAll(`{${k}}`, String(v));
      });
    }
    return text;
  };
}

const LOCALE_STORAGE_KEY = 'soni-samaj-locale';

export function getStoredLocale(): Locale {
  if (typeof window === 'undefined') return 'en';
  const stored = localStorage.getItem(LOCALE_STORAGE_KEY);
  return stored === 'hi' ? 'hi' : 'en';
}

export function storeLocale(locale: Locale) {
  if (typeof window !== 'undefined') {
    localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  }
}
